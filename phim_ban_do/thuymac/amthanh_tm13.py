drop(M,.9,.9);gong(M,1.6,.45)
drum(M,sb(2,1)+.3,.35);brush(M,sb(2,2)-.6,1.0,.3)
drum(M,sb(3,1),.5);gong(M,sb(3,1)+.2,.3)
gong(M,T[4]-3.4,.4);stamp(M,T[4]-2.4,.4)
march(M,T[5],E[5],.12)
drum(M,T[6]+.2,.45);drum(M,sb(6,1)-.2,.3)
drum(M,T[7]+.1,.6);shouts(M,T[7]+.6,2.5,.3);stamp(M,T[7]+.6,.4)
for k in range(3): drum(M,T[8]+.3+k*1.5,.45)
gong(M,sb(9,1),.35)
whoosh(M,T[10]-.4,1.1,.4);march(M,T[10],E[11],.25);stamp(M,T[10]+.8,.4)
drum(M,T[12]+.2,.7);shouts(M,T[12]+1.4,4.0,.45);drum(M,T[12]+2,.6)
march(M,T[13],E[13],.2)
wind(M,T[14],E[15],.3);stamp(M,sb(15,1)+.6,.4)
brush(M,sb(16,1),.9,.3);brush(M,sb(16,1)+2.5,.9,.3);brush(M,sb(16,1)+5,.9,.3)
drum(M,T[17]+.6,.4);drum(M,T[17]+1.9,.4);drum(M,T[17]+3.2,.4)
gong(M,T[18]+.4,.4);stamp(M,sb(18,1)+.4,.45)
gong(M,sb(19,1),.5)
wind(M,T[20]-.2,E[20],.4)
for k in range(3): drum(M,sb(22,1)+k*1.4,.4)
drum(M,T[23]+.5,.4);gong(M,E[23]+.4,.4)
finish(M,V,'/tmp/gen/bd/out/am_tm13.wav')
