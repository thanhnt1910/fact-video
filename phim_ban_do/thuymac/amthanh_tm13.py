from amchung import *
import dai_tm13 as D
V=D.V;T,E=V.T,V.E;sb=D.sb
M=Mix(V.TOTAL,30)
wind(M,.2,V.TOTAL-.5,.14)
music(M,1.2,T[4]-.5,'bi',.75)
music(M,T[4],T[6],'mo',.75)
music(M,sb(6,1)+.6,T[10]-.3,'trang',.8)
music(M,T[10],T[13],'cang',.9)
music(M,T[13],T[17],'bi',.8)
music(M,T[17],T[20],'cang',.75)
music(M,T[20],T[22],'mo',.75)
