# Âm thanh tm16 bản 2 (khớp dai_tm16.py): giọt mực và cồng mở đầu; nét cọ khi dải giấy câu nói hiện ra (hình ảnh lặp lại);
# trống trầm khi Lữ Đại chém Sĩ Huy; tiếng bước chân đoàn người ra hàng; quét mực và trống trận khi bà nổi dậy; voi và tiếng hô ở đoạn 11.
from amchung import *
import dai_tm16 as D
V=D.V;T,E=V.T,V.E;sb=D.sb
M=Mix(V.TOTAL,30)
wind(M,.2,V.TOTAL-.5,.14)
music(M,1.2,T[4]-.5,'bi',.75)
music(M,T[4],T[8],'mo',.75)
music(M,sb(8,1)-.4,T[12],'cang',.9)
music(M,T[12],T[16],'bi',.8)
music(M,T[16],T[19],'mo',.75)
music(M,T[19],V.TOTAL-1,'trang',.85)
drop(M,.9,.9);gong(M,1.6,.45)
brush(M,T[2]+.2,1.0,.3);brush(M,T[2]+1.0,1.0,.3);stamp(M,sb(2,1)+.6,.4)
brush(M,T[3]+.6,.8,.25)
gong(M,T[4]-3.4,.4);stamp(M,T[4]-2.4,.4);stamp(M,T[4]+.6,.35)
march(M,T[5],sb(5,1),.15);drum(M,sb(5,1)+(E[5]-sb(5,1))*.6,.5)
march(M,T[6],E[6],.12)
march(M,T[7],E[7],.3)
whoosh(M,sb(8,1)-.6,1.1,.45);drum(M,sb(8,1)+.6,.6);shouts(M,sb(8,1)+1.2,2.5,.35)
drum(M,sb(9,1),.45)
drum(M,T[11]+.3,.7);march(M,T[11],T[11]+3,.4);shouts(M,T[11]+2.8,3.5,.45);drum(M,T[11]+3,.8)
for k in range(3): stamp(M,sb(12,1)+.2+k*((E[12]-sb(12,1)-.6)/3),.45)
drum(M,T[13]+.3,.5);shouts(M,T[13]+.4,2.0,.3)
gong(M,T[14]+.3,.4)
brush(M,T[16]+.3,1.0,.3)
for k in range(3): stamp(M,T[16]+1.6+k*.8,.35)
brush(M,sb(17,1)+1.5,.8,.35)
for k in range(3): stamp(M,sb(18,1)+k*.8,.3)
brush(M,sb(18,1)+2.6,1.0,.3)
wind(M,T[19],E[19],.35);stamp(M,sb(19,1)+.2,.4)
drum(M,T[20]+.5,.4);gong(M,E[20]+.4,.4)
finish(M,V,'/tmp/gen/bd/out/am_tm16.wav')
