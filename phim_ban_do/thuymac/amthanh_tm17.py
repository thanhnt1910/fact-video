# Âm thanh tm17 (khớp cảnh dai_tm17.py): giọt mực, gió núi, nhạc theo chương; lặng nhịp trước câu nhấn đoạn 3 và trước câu kết khí độc (đoạn 26);
# trống, tiếng hô ở trận; triện đóng khi bộ đếm ba lần đóng dấu; cồng ở Vạn Xuân; nét cọ khi quét cảnh, khi viết cuộn sử.
from amchung import *
import dai_tm17 as D
V=D.V;T,E,mid=V.T,V.E,V.mid;sb=D.sb
M=Mix(V.TOTAL,30)
wind(M,.2,V.TOTAL-.5,.14)
q3=sb(3,1)
music(M,1.2,T[3]-.2,'bi',.75)
music(M,q3+.4,T[12]-.3,'mo',.8)
music(M,T[12],T[17],'cang',.85)
music(M,T[17],T[21],'mo',.8)
music(M,T[21],T[23],'trang',.85)
music(M,T[23],T[26]-.5,'cang',.9)
music(M,sb(26,1)+.3,V.TOTAL-1,'bi',.8)
drop(M,.9,.9);gong(M,1.6,.45)
brush(M,sb(2,0)+.3,.8,.3,-.4);brush(M,sb(2,1)+.1,.8,.3,.4);stamp(M,sb(2,1)+1.2,.45)
drum(M,T[3]+.2,.35);march(M,T[3],q3-.6,.18)
whoosh(M,q3-.6,1.1,.45);brush(M,q3-.5,1.0,.35)
march(M,T[4],E[4],.15);brush(M,sb(5,1),1.0,.3);stamp(M,sb(7,1)+.2,.4)
shouts(M,T[9]+.5,2.0,.25);drum(M,T[10],.5);shouts(M,T[10]+.3,1.5,.3);whoosh(M,sb(10,1)+1,1.0,.35)
gong(M,T[11]+.4,.4)
march(M,T[12],E[12],.3);stamp(M,sb(13,1)+.2,.55)
wind(M,T[14]-.2,E[16],.35)
for ts,_ in D.DEM(): stamp(M,ts,.6)
gong(M,T[17]+.3,.35)
drum(M,T[18]+.3,.6);shouts(M,T[18]+.4,3.0,.35)
drum(M,T[20],.7);shouts(M,T[20]+.6,3.5,.4)
gong(M,sb(21,1),.6);gong(M,sb(21,1)+2.5,.35)
march(M,T[23],E[23],.3);drum(M,T[24],.8);shouts(M,T[24]+.3,4.0,.45);drum(M,T[24]+2,.6)
march(M,T[25],E[25],.2)
wind(M,T[26]-.2,E[27],.4);stamp(M,T[27]+.6,.35)
gong(M,T[29]+.2,.4)
finish(M,V,'/tmp/gen/bd/out/am_tm17.wav')
