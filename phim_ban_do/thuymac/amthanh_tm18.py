# Âm thanh tm18 (khớp dai_tm18.py): giọt mực và cồng mở đầu; nét cọ mỗi khi cuộn sử hiện chữ (hình ảnh lặp lại);
# tiếng trống khi xưng vua; tiếng ngựa và bước chân khi quân nhà Đường đi trên đường cũ; quét mực và trận ở đoạn 16–17;
# lặng gió ở gò xác; nét cọ dài khi viết hai chữ châu dân (đoạn 25).
from amchung import *
import dai_tm18 as D
V=D.V;T,E=V.T,V.E;sb=D.sb
M=Mix(V.TOTAL,30)
wind(M,.2,V.TOTAL-.5,.14)
music(M,1.2,T[4]-.5,'bi',.75)
music(M,T[4],T[9],'mo',.75)
music(M,T[9],T[13],'trang',.8)
music(M,T[13],T[16],'cang',.8)
music(M,T[16],sb(17,1),'cang',.95)
music(M,sb(17,1)+.5,T[22],'bi',.75)
music(M,T[22],T[25],'mo',.75)
music(M,T[25],V.TOTAL-1,'trang',.85)
drop(M,.9,.9);gong(M,1.6,.45)
brush(M,T[2]+.2,.9,.3);brush(M,T[2]+1.2,.9,.3);stamp(M,sb(2,1)+.2,.35)
brush(M,T[3]+.6,.8,.35)
gong(M,T[4]-3.4,.4);stamp(M,T[4]-2.4,.4)
march(M,T[5],E[5],.1)
brush(M,T[8]+.4,.8,.3);brush(M,sb(8,1),.8,.3)
drum(M,T[9]+.3,.5);stamp(M,T[9]+.6,.45);shouts(M,sb(9,1)+.3,2.0,.3)
for k in range(4): stamp(M,sb(10,1)+k*.6,.25)
drum(M,T[11]+.2,.5);shouts(M,T[11]+.5,2.0,.3)
stamp(M,T[12]+.4,.3);stamp(M,sb(12,1),.35)
gong(M,T[13]+.3,.35)
march(M,T[14],E[14],.2)
march(M,T[15],E[15],.25)
whoosh(M,T[16]-.4,1.1,.45);march(M,T[16],E[16],.35)
drum(M,T[17]+.2,.8);shouts(M,T[17]+.6,3.0,.45);drum(M,T[17]+1.4,.6)
wind(M,sb(17,1),E[17]+1,.45)
brush(M,sb(18,1),.8,.3);brush(M,sb(18,1)+(E[18]-sb(18,1))*.45,.8,.3)
stamp(M,T[19]+.8,.45)
brush(M,sb(20,1),.8,.3);stamp(M,sb(20,1)+1.2,.45)
brush(M,T[21]+.6,1.4,.35);brush(M,T[21]+1.8,.8,.3)
stamp(M,T[22]+.4,.35)
for k in range(3): stamp(M,T[23]+.4+k*.4,.2)
march(M,T[24],E[24],.2)
gong(M,sb(25,1),.35)
brush(M,T[27]+.8,.7,.35);brush(M,T[27]+1.6,1.4,.4);gong(M,T[27]+3.0,.4)
wind(M,T[28],E[28],.3)
gong(M,E[29]+.4,.4)
finish(M,V,'/tmp/gen/bd/out/am_tm18.wav')
