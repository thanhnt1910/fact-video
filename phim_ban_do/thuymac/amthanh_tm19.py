# Âm thanh tm19 (khớp dai_tm19.py): giọt mực và cồng mở đầu; nét cọ mỗi khi tấm biển hoặc cuộn sử hiện chữ (hình ảnh lặp lại);
# trống và tiếng hô ở trận đánh mãi không thắng (đoạn 9) và lúc vây phủ thành (đoạn 11–12); lặng gió khi ông mất (đoạn 14);
# nét cọ khi tấm biển hiện "Bố Cái" (đoạn 16–17); cồng kết.
from amchung import *
import dai_tm19 as D
V=D.V;T,E=V.T,V.E;sb=D.sb
M=Mix(V.TOTAL,30)
wind(M,.2,V.TOTAL-.5,.14)
music(M,1.2,T[4]-.5,'bi',.75)
music(M,T[4],T[8],'mo',.75)
music(M,T[8],T[13],'cang',.85)
music(M,T[13],T[14],'trang',.8)
music(M,T[14],T[16],'bi',.75)
music(M,T[16],T[19],'trang',.8)
music(M,T[19],T[24],'mo',.75)
music(M,T[24],V.TOTAL-1,'trang',.85)
drop(M,.9,.9);gong(M,1.6,.45)
brush(M,sb(1,1)+.1,.8,.3)
march(M,T[2],sb(2,1),.15);brush(M,sb(2,1)+.1,.9,.3)
brush(M,T[3]+.3,.8,.3)
gong(M,T[4]-3.4,.4);stamp(M,T[4]-2.4,.4)
stamp(M,sb(5,1)+.3,.3)
for k in range(4): stamp(M,sb(6,1)+.4+k*.7,.2)
drum(M,T[7]+.3,.4);march(M,T[7],E[7],.15)
brush(M,sb(8,1),.8,.3)
whoosh(M,T[9]-.3,1.0,.4);drum(M,T[9]+.6,.6);shouts(M,T[9]+.9,2.5,.35);drum(M,T[9]+1.6,.5)
brush(M,sb(10,1)+.2,1.4,.3)
drum(M,sb(11,1)+.2,.6);shouts(M,sb(11,1)+.5,2.0,.35);stamp(M,sb(11,1)+.6,.4)
gong(M,T[12]+.3,.3);drum(M,sb(12,1),.6);shouts(M,sb(12,1)+.3,2.2,.4)
stamp(M,T[13]+.6,.35);brush(M,T[13]+1.2,1.2,.3);stamp(M,T[13]+2.5,.4)
wind(M,T[14],E[14]+.5,.4)
brush(M,T[15]+.2,.8,.3);brush(M,T[15]+.9,.8,.3)
brush(M,sb(16,1)+.2,1.2,.35);gong(M,sb(16,1)+.6,.35)
brush(M,T[17]+.3,.9,.35);stamp(M,T[17]+.8,.25);stamp(M,T[17]+1.6,.25)
march(M,T[19],sb(19,1)+1,.2)
stamp(M,sb(20,1)+.4,.4)
brush(M,sb(21,1),.6,.3);brush(M,sb(21,1)+.9,.6,.3)
brush(M,T[22]+.8,.7,.35);brush(M,sb(22,1),.9,.35)
brush(M,sb(24,1),.8,.3)
gong(M,T[25]+.5,.35);brush(M,T[25]+1.2,1.4,.35)
gong(M,E[25]+.4,.4)
finish(M,V,'/tmp/gen/bd/out/am_tm19.wav')
