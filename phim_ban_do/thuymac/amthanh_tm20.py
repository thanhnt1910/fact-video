# Âm thanh tm20 (khớp dai_tm20.py): giọt mực và cồng mở đầu; bước quân và trống khi quay quân giữa đêm (đoạn 1, 14);
# nét cọ khi hai cuộn sử hiện chữ (hình ảnh lặp lại: 2, 11, 26, 30, 33); trận vây phủ thành (15) và trận Toàn thư chép (30);
# gió lặng khi Lý Tượng Cổ bị giết (16); vó ngựa đưa tin (18) và lúc Hàn Ước bỏ chạy (32); cồng kết.
from amchung import *
import dai_tm20 as D
V=D.V;T,E=V.T,V.E;sb=D.sb
M=Mix(V.TOTAL,30)
wind(M,.2,V.TOTAL-.5,.14)
music(M,1.2,T[4]-.5,'cang',.8)
music(M,T[4],T[9],'mo',.75)
music(M,T[9],T[13],'trang',.8)
music(M,T[13],T[16],'cang',.9)
music(M,T[16],T[18],'bi',.75)
music(M,T[18],T[22],'mo',.75)
music(M,T[22],T[26],'bi',.75)
music(M,T[26],T[30],'cang',.85)
music(M,T[30],T[33],'trang',.8)
music(M,T[33],V.TOTAL-1,'bi',.8)
drop(M,.9,.9);gong(M,1.6,.45)
march(M,1.4,sb(1,1),.2);whoosh(M,sb(1,1),.8,.35);drum(M,sb(1,1)+.3,.45);march(M,sb(1,1)+.3,E[1]-sb(1,1),.25)
brush(M,T[2]+.4,.8,.3);brush(M,T[2]+1.2,.8,.3)
gong(M,T[4]-3.4,.4);stamp(M,T[4]-2.4,.4)
brush(M,sb(4,1),1.2,.3)
stamp(M,sb(7,1)+.2,.3);brush(M,sb(7,1)+.4,1.6,.3)
brush(M,sb(8,1)+.6,.6,.3)
march(M,T[9],E[9],.15);drum(M,sb(9,1),.35)
brush(M,sb(10,1)+.3,.8,.3)
march(M,T[11],E[11],.2);brush(M,sb(11,1)+.2,.7,.3);brush(M,sb(11,1)+1.0,.7,.3)
stamp(M,T[12]+.6,.3)
whoosh(M,T[14]-.3,1.0,.4);march(M,T[14],E[14],.3);drum(M,T[14]+.8,.5);drum(M,sb(14,1),.6)
drum(M,T[15]+.3,.6);shouts(M,T[15]+.6,3,.35);clangs(M,T[15]+1.6,E[15]-T[15]-1.5,.3)
for k in range(4): stamp(M,T[15]+.4+k*((sb(15,1)-T[15])/4),.22)
stamp(M,sb(15,2)+.3,.4)
wind(M,T[16],E[16]+.4,.4);thump(M,T[16]+1.2,.4)
whoosh(M,sb(17,1),.8,.35)
hooves(M,T[18],E[18]-T[18],.3)
for k in range(4): stamp(M,sb(18,1)+.2+k*.6,.2)
gong(M,T[19]+.3,.3);brush(M,sb(19,1)+.8,.6,.3);brush(M,sb(19,1)+1.8,.6,.3)
brush(M,sb(20,1),1.6,.25)
stamp(M,sb(21,1)+.3,.4);drum(M,sb(21,2),.45)
steps(M,T[22]+.2,T[22]+2.4,.2)
whoosh(M,T[23]+1.0,.7,.3)
steps(M,T[24],E[24],.2)
thump(M,sb(25,1)+.6,.3)
gong(M,T[26]+.3,.35);brush(M,sb(26,1),1.0,.3)
drum(M,T[27]+.3,.5);creak(M,T[27]+.6,1.4,.5);shouts(M,T[27]+1.0,2,.35);thump(M,sb(27,1)+.6,.4)
brush(M,T[28]+.9,.6,.3)
brush(M,T[29]+.3,2.0,.3);whoosh(M,sb(29,1),.6,.3);whoosh(M,sb(29,2),.6,.3)
brush(M,T[30]+.4,.8,.3);drum(M,sb(30,1),.5);shouts(M,sb(30,1)+.3,2,.3);clangs(M,sb(30,1)+1.4,2,.25)
hooves(M,T[32],E[32]-T[32],.3);shouts(M,T[32]+1,1.5,.25);stamp(M,T[32]+.6,.35)
brush(M,T[33]+.3,.8,.3);brush(M,sb(33,1),.8,.3)
gong(M,T[34]+.5,.35);brush(M,T[34]+1.2,1.4,.35)
gong(M,E[34]+.4,.4)
finish(M,V,'/tmp/gen/bd/out/am_tm20.wav')
